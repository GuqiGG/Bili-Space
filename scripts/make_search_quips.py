def build():
    lines = []
    seen = set()
    def add(text):
        text = text.strip()
        if text and len(text) <= 22 and text not in seen:
            seen.add(text); lines.append(text)
    for t in HAND: add(t)
    pick = random.Random(7)
    # Each kind is capped so no single template dominates what people see.
    for yi, ji in pick.sample(list(itertools.product(YI, JI)), 900): add(f"今日宜{yi}，忌{ji}")
    for t in TIPS: add("小技巧：" + t)
    for when, watch in list(itertools.product(WHEN, WATCH)): add(f"{when}的时候，适合看{watch}")
    for who, do in itertools.product(RUMOR_WHO, RUMOR_DO): add(f"据不可靠消息：{who}{do}")
    for who, do in itertools.product(ANIMAL, ANIMAL_DO): add(f"{who}{do}")
    for t in BOX_SAYS: add(f"搜索框：{t}")
    for p, do in itertools.product(PCT, PCT_DO): add(f"{p}% 的人搜完都{do}")
    return lines

if __name__ == "__main__":
    lines = build()
    random.Random(62).shuffle(lines)
